import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const c=vm.createContext({URL});
vm.runInContext(fs.readFileSync(new URL('../student-gender-icons.js',import.meta.url),'utf8'),c);
const api=c.PortalStudentGender, doc=(id,data)=>({id,data:()=>data});
const docs=[doc('one',{studentName:'테스트',school:'학교A',gender:'male'}),doc('two',{studentName:'테스트',school:'학교B',gender:'female'}),doc('suffix',{name:'테스트b',gender:'female'}),doc('unset',{name:'미선택',gender:''})];
assert.equal(api.resolve({name:'테스트'},docs),'');
assert.equal(api.resolve({name:'테스트',school:'학교A'},docs),'male');
assert.equal(api.resolve({name:'이전이름',id:'two'},docs),'female');
assert.equal(api.resolve({name:'테스트b'},docs),'female');
assert.equal(api.resolve({name:'미선택'},docs),'');
assert.equal(api.resolve({name:'없음'},docs),'');
const old=doc('old',{lookupKey:'student-gender:male',imageUrl:'https://example.com/old.png',updatedAtMs:1});
const fresh=doc('fresh',{lookupKey:'student-gender:male',imageUrl:'https://example.com/new.png',updatedAt:{seconds:2}});
assert.equal(api.assets([fresh,old]).get('student-gender:male'),'https://example.com/new.png');
assert.equal(api.assets([old,doc('disabled',{...fresh.data(),status:'INACTIVE'})]).get('student-gender:male'),'');
assert.equal(api.assets([doc('bad',{lookupKey:'student-gender:female',imageUrl:'javascript:alert(1)'})]).get('student-gender:female'),'');
assert(!api.render('<img src=x onerror=alert(1)>',{studentId:'" onmouseover="x'}).includes('<img'));
assert(api.render('이름b',{},'이름').includes('data-gender-name="이름b"'));
const source=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
assert(source.includes('student-gender-icons.js?v=521'));
assert((source.match(/renderPortalStudentName_\(/g)||[]).length>=50);
assert(!source.includes('data-gender-name="${escapeHtml_(row.teacher'));
console.log('PASS gender source, unset, ambiguous names, ID priority, suffix, latest URL, inactive, URL safety, escaping and renderer coverage');
